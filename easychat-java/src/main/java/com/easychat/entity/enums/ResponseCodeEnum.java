package com.easychat.entity.enums;

/**
 * 统一错误码分段规范
 *
 * | 段          | 域        | 说明                    |
 * |------------|----------|-----------------------|
 * | 0          | 成功       | 0                      |
 * | 1000-1999  | 通用       | 参数、系统、通用错误              |
 * | 2000-2099  | 鉴权域     | Token、会话、认证相关            |
 * | 2100-2199  | 用户域     | 用户信息、注册、密码              |
 * | 2200-2299  | 聊天域     | 消息、会话                   |
 * | 2300-2399  | 群组域     | 群组操作、群成员                |
 * | 2400-2499  | 好友域     | 好友关系、好友申请              |
 * | 2500-2599  | 朋友圈域    | 动态、评论、点赞                |
 * | 2600-2699  | 文件域     | 文件上传、下载                 |
 */
public enum ResponseCodeEnum {

    // ======================== 成功 ========================
    CODE_200(0, "success"),

    // ======================== 通用 1000-1999 ========================
    CODE_1001(1001, "请求参数错误"),
    CODE_1002(1002, "系统内部错误，请联系管理员"),
    CODE_1003(1003, "资源不存在"),

    // ======================== 鉴权域 2000-2099 ========================
    CODE_2001(2001, "登录超时，请重新登录"),
    CODE_2002(2002, "Token无效"),
    CODE_2003(2003, "无权限操作"),

    // ======================== 用户域 2100-2199 ========================
    CODE_2101(2101, "用户不存在"),
    CODE_2102(2102, "信息已经存在"),
    CODE_2103(2103, "密码错误"),
    CODE_2104(2104, "文件不存在"),

    // ======================== 聊天域 2200-2299 ========================
    CODE_2201(2201, "消息不存在"),
    CODE_2202(2202, "无权限操作该消息"),

    // ======================== 群组域 2300-2399 ========================
    CODE_2301(2301, "您不是对方的好友，请先向好友发送朋友验证申请"),
    CODE_2302(2302, "你已经不在群聊，请重新加入群聊"),
    CODE_2303(2303, "群组不存在"),
    CODE_2304(2304, "您已不在该群组中"),

    // ======================== 好友域 2400-2499 ========================
    CODE_2401(2401, "非好友关系"),
    CODE_2402(2402, "好友申请已存在"),

    // ======================== 朋友圈域 2500-2599 ========================
    CODE_2501(2501, "动态不存在"),
    CODE_2502(2502, "无权限操作该动态"),

    // ======================== 文件域 2600-2699 ========================
    CODE_2601(2601, "文件不存在"),
    CODE_2602(2602, "文件上传失败"),
    CODE_2603(2603, "文件大小超出限制"),
    CODE_2604(2604, "不支持的文件类型"),

    // ======================== 向后兼容（旧码，逐步废弃） ========================
    /** @deprecated 使用 CODE_1003 替代 */
    @Deprecated
    CODE_404(404, "请求地址不存在"),
    /** @deprecated 使用 CODE_1002 替代 */
    @Deprecated
    CODE_500(500, "服务器返回错误，请联系管理员"),
    /** @deprecated 使用 CODE_1001 替代 */
    @Deprecated
    CODE_600(600, "请求参数错误"),
    /** @deprecated 使用 CODE_2102 替代 */
    @Deprecated
    CODE_601(601, "信息已经存在"),
    /** @deprecated 使用 CODE_2104 替代 */
    @Deprecated
    CODE_602(602, "文件不存在"),
    /** @deprecated 使用 CODE_2001 替代 */
    @Deprecated
    CODE_901(901, "登录超时"),
    /** @deprecated 使用 CODE_2301 替代 */
    @Deprecated
    CODE_902(902, "您不是对方的好友，请先向好友发送朋友验证申请"),
    /** @deprecated 使用 CODE_2302 替代 */
    @Deprecated
    CODE_903(903, "你已经不在群聊，请重新加入群聊");

    private final Integer code;
    private final String msg;

    ResponseCodeEnum(Integer code, String msg) {
        this.code = code;
        this.msg = msg;
    }

    public Integer getCode() {
        return code;
    }

    public String getMsg() {
        return msg;
    }
}
